import assert from "node:assert/strict";
import test from "node:test";
import { InputError } from "../src/names.js";
import { requireRpc, rpcCatalog } from "../src/rpc.js";

test("the RPC catalog includes implemented controller methods and omits stubs and streams", () => {
  const methods = rpcCatalog();
  const names = new Set(methods.map((item) => `${item.service}/${item.method}`));
  assert.equal(names.has("controller/listVms"), true);
  assert.equal(names.has("controller/createVm"), true);
  assert.equal(names.has("controller/listNodes"), true);
  assert.equal(names.has("controller/getPkiStatus"), true);
  assert.equal(names.has("controller-admin/getReplicationStatus"), true);
  assert.equal(names.has("node-compute/listImages"), true);
  assert.equal(names.has("node-admin/listDisks"), true);
  assert.equal(names.has("node-info/getNodeInfo"), true);
  assert.equal(names.has("node-compute/pullImage"), false);
  assert.equal(names.has("node-compute/createVm"), false);
  assert.equal(names.has("controller/attachVmConsole"), false);
  assert.equal(names.has("node-admin/attachVmConsole"), false);
  assert.equal(names.has("node-admin/uploadImageStream"), false);
  assert.equal(names.has("provisioning/listImages"), true);
  assert.equal(names.has("provisioning/listMachines"), true);
  assert.equal(names.has("provisioning/setBootTarget"), true);
  assert.equal(names.has("provisioning/discoverMachine"), true);
  assert.equal(names.has("provisioning/powerControl"), true);
  assert.equal(names.has("provisioning/downloadImage"), true);
  assert.equal(names.has("provisioning/scanNetwork"), true);
  assert.equal(names.has("provisioning/listIpmiCommands"), true);
  assert.equal(names.has("provisioning/wakeOnLan"), true);
  assert.equal(names.has("provisioning/upsertDhcpDns"), true);
  assert.equal(names.has("controller/getHaStatus"), true);
  assert.equal(names.has("controller/listKubernetesClusters"), true);
  assert.equal(names.has("controller/createObjectStore"), true);
  assert.equal(names.has("node-storage/snapshotVolume"), true);
  assert.equal(names.has("node-admin/getCephDf"), true);
  assert.equal(names.has("vault/listInventory"), true);
  assert.equal(names.has("vault/getVaultStatus"), true);
  assert.equal(names.has("vault-mover/openLease"), true);
  assert.equal(names.has("vault-install/listDisks"), true);
  assert.equal(names.has("controller/readVolumeBlocks"), false);
  assert.equal(names.has("vault/watchEvents"), false);
  assert.equal(names.has("provisioning/issueServerCertificate"), false);
  assert.equal(names.has("provisioning/getCaBundle"), false);
  const listImages = methods.find((item) => item.service === "provisioning" && item.method === "listImages");
  assert.equal(listImages?.readOnly, true);
  const power = methods.find((item) => item.service === "provisioning" && item.method === "powerControl");
  assert.equal(power?.readOnly, false);
  const scan = methods.find((item) => item.service === "provisioning" && item.method === "scanNetwork");
  assert.equal(scan?.readOnly, true);
  const wake = methods.find((item) => item.service === "provisioning" && item.method === "wakeOnLan");
  assert.equal(wake?.readOnly, false);
  const listVms = methods.find((item) => item.service === "controller" && item.method === "listVms");
  assert.equal(listVms?.readOnly, true);
  const createVm = methods.find((item) => item.service === "controller" && item.method === "createVm");
  assert.equal(createVm?.readOnly, false);
});

test("an omitted stub is rejected before any dial", () => {
  assert.throws(() => requireRpc("node-compute", "pullImage"), InputError);
  assert.throws(() => requireRpc("controller", "attachVmConsole"), InputError);
  assert.throws(() => requireRpc("provisioning", "issueNodeCertificate"), InputError);
});
